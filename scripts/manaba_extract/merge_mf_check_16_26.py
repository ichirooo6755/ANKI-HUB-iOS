def norm(s: str) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip()


def dedup_key(item: dict) -> str:
    stem = norm(item.get("text", ""))
    choices = "|".join(sorted(norm(c) for c in item.get("select", [])))
    return f"{stem}::{choices}"


def next_id(prefix: str, existing: list, added: list) -> str:
    nums = []
    for it in existing + added:
        m = re.match(rf"{re.escape(prefix)}(\d+)", it.get("id", ""))
        if m:
            nums.append(int(m.group(1)))
    n = max(nums, default=0) + 1
    return f"{prefix}{n:02d}"


def main():
    data = json.loads(MANEFI.read_text(encoding="utf-8"))
    seen = {dedup_key(it) for it in data}

    recat = 0
    for it in data:
        nid = it.get("id", "")
        if nid in RECATEGORIZE:
            it["category"] = RECATEGORIZE[nid]
            recat += 1

    added: list[dict] = []
    skipped = 0
    by_cat: dict[str, int] = {}

    for raw in NEW_ITEMS:
        item = {"text": raw["text"], "select": raw["select"], "category": raw["category"]}
        key = dedup_key(item)
        if key in seen:
            skipped += 1
            continue
        seen.add(key)
        prefix = "mf-uc" if "理解度チェック" in raw["category"] else "mf-fc"
        entry = {
            "id": next_id(prefix, data, added),
            "category": raw["category"],
            "text": raw["text"],
            "select": raw["select"],
        }
        added.append(entry)
        by_cat[raw["category"]] = by_cat.get(raw["category"], 0) + 1

    data.extend(added)
    MANEFI.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"recategorized: {recat}")
    print(f"added: {len(added)} skipped_dup: {skipped}")
    for cat, n in sorted(by_cat.items()):
        print(f"  {cat}: +{n}")
    print(f"total manefi: {len(data)}")


if __name__ == "__main__":
    main()
